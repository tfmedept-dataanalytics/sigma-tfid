const TABLES = { id: {}, en: EN };

export function translator(lang) {
  const table = TABLES[lang] || {};
  /**
   * t(key) menerjemahkan satu frasa utuh.
   * t(key, vars) menerjemahkan lalu mengisi placeholder {nama}.
   *
   * Placeholder dipakai agar kalimat yang memuat angka tetap menjadi SATU
   * frasa yang dapat diterjemahkan. Menyusun kalimat dari potongan JSX
   * membuatnya terpecah menjadi beberapa node teks dan tidak pernah cocok
   * dengan kamus — itulah sebab narasi panjang sebelumnya tidak ikut berganti
   * bahasa meski labelnya sudah berganti.
   */
  return function t(key, vars) {
    const base = Object.prototype.hasOwnProperty.call(table, key) ? table[key] : key;
    if (!vars) return base;
    return base.replace(/\{(\w+)\}/g, (m, k) =>
      (vars[k] === undefined || vars[k] === null ? m : String(vars[k])));
  };
}

